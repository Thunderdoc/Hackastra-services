    /**
     * Download existing students in the bulk-edit column set (ids
     * resolved back to names), so the office edits real current data
     * and re-uploads — the round-trip the roster export can't do.
     */
    public function exportsStudents()
    {
        $records = StudentRecord::with(['user', 'my_class', 'section'])
            ->where('grad', 0)->orderBy('my_class_id')->orderBy('id')->get();

        $bgNames = BloodGroup::pluck('name', 'id');
        $nalNames = Nationality::pluck('name', 'id');
        $stateNames = State::pluck('name', 'id');
        $lgaNames = Lga::pluck('name', 'id');
        $dormNames = Dorm::pluck('name', 'id');
        $sections = Section::pluck('name', 'id');
        $parents = \App\User::where('user_type', 'parent')->pluck('email', 'id');

        // Values are emitted in StudentBulkController::COLUMNS order —
        // the same order as the header row CsvExport writes (Loop 111
        // repair: this map used to lead with adm_no, shifting every
        // value one column left under its header).
        $rows = $records->map(function ($sr) use ($bgNames, $nalNames, $stateNames, $lgaNames, $dormNames, $sections, $parents) {
            $u = $sr->user;
            return [
                $u ? $u->name : '',
                $u ? $u->email : '',
                $u ? $u->gender : '',
                $u ? $u->phone : '',
                $u ? $u->phone2 : '',
                $u ? $u->dob : '',
                $u ? $u->address : '',
                $u ? ($nalNames[$u->nal_id] ?? '') : '',
                $u ? ($stateNames[$u->state_id] ?? '') : '',
                $u ? ($lgaNames[$u->lga_id] ?? '') : '',
                $u ? ($bgNames[$u->bg_id] ?? '') : '',
                $sr->my_class ? $sr->my_class->name : '',
                $sections[$sr->section_id] ?? '',
                $sr->my_parent_id ? ($parents[$sr->my_parent_id] ?? '') : '',
                $sr->year_admitted,
                $sr->dorm_id ? ($dormNames[$sr->dorm_id] ?? '') : '',
                $sr->dorm_room_no,
                $sr->house,
                $sr->adm_no,
            ];
        });

        return CsvExport::download('students-existing-records.csv', StudentBulkController::COLUMNS, $rows);
    }
}

