    protected function flowData($module, $mode, $title, $intro, $templateUrl, $columns, $required): array
    {
        return [
            'module' => $module,
            'mode' => $mode,
            'flow_title' => $title,
            'flow_intro' => $intro,
            'template_url' => $templateUrl,
            'columns' => $columns,
            'required' => $required,
        ];
    }

    /**************** UPLOAD → STAGE → VALIDATE ****************/

    public function upload(Request $req)
    {
        $req->validate([
            'module' => 'required|in:students,staff',
            'mode' => 'required|in:add,update',
            'bulk_file' => 'required|file|max:10240',
        ]);

        $module = $req->input('module');
        $mode = $req->input('mode');
        if (!isset(BulkImportService::flows()["{$module}:{$mode}"])) {
            return back()->with('flash_danger', 'That bulk flow is not available.');
        }

        $file = $req->file('bulk_file');
        // Wave 10 — .xlsx is accepted now (XlsxReader, content-sniffed
        // in staging). The extension only decides the rejection
        // message: a ZIP renamed to .csv is an Excel file, not a
        // corrupt CSV, and an .xlsx that is not a ZIP is corrupt.
        $ext = strtolower($file->getClientOriginalExtension());
        $head = file_get_contents($file->getRealPath(), false, null, 0, 4);
        if ($head === "PK\x03\x04") {
            if (!in_array($ext, ['csv', 'xlsx'], true)) {
                return back()->with('flash_danger', 'Please upload a .csv or .xlsx file. You can download the template for this flow from the Bulk Management hub.');
            }
        } elseif ($ext === 'xlsx') {
            return back()->with('flash_danger', 'That .xlsx file does not look like an Excel workbook — it may be corrupt. Please re-save it from Excel and upload again.');
        } elseif ($ext !== 'csv') {
            return back()->with('flash_danger', 'Please upload a .csv or .xlsx file. You can download the template for this flow from the Bulk Management hub.');
        }

        [$job, $warning] = $this->service->createJob($req->user(), $module, $mode, $file);

        $error = $this->service->stageAndValidate($job);
        if ($error !== null) {
            return redirect()->route('bulk.index')
                ->with('flash_danger', "Job #{$job->id} could not be prepared: {$error}");
        }

        $msg = "Job #{$job->id} is ready for review: {$job->total_rows} row(s) — "
            . "{$job->create_count} to create, {$job->update_count} to update, "
            . "{$job->skip_count} to skip, {$job->error_count} with errors. Nothing has been saved yet.";
        if ($warning) {
            $msg .= ' ' . $warning;
        }

        return redirect()->route('bulk.jobs.show', $job->id)->with('flash_success', $msg);
    }

    /**************** PREVIEW / PROGRESS / RESULT ****************/

    public function show(BulkImportJob $job)
    {
        $data['job'] = $job;
        $data['invalid_rows'] = $job->rows()->where('verdict', 'invalid')->orderBy('row_number')->limit(200)->get();
        $data['problem_rows'] = $job->rows()->whereIn('verdict', ['duplicate', 'unmatched', 'failed'])->orderBy('row_number')->limit(200)->get();
        $data['changed_rows'] = $job->mode === 'update'
            ? $job->rows()->whereIn('verdict', ['valid_update', 'applied'])->whereNotNull('changes')->orderBy('row_number')->limit(200)->get()
                ->filter(function ($r) { return !empty($r->changes); })->values()
            : collect();
        $data['pending_count'] = (int) $job->pendingRows()->count();
        $data['applied_rows_count'] = (int) $job->rows()->where('verdict', 'applied')->count();
        $data['rolled_back_count'] = (int) $job->rows()->where('verdict', 'rolled_back')->count();
        $data['can_write'] = Qs::userIsAdmin();

        return view('pages.support_team.bulk.job', $data);
    }

    public function confirm(Request $req, BulkImportJob $job)
    {
        if (!$this->service->confirm($job, $req->input('confirm_token'))) {
            return back()->with('flash_danger', 'This confirmation is no longer valid — it may already have been used, or the job is not waiting for confirmation. Nothing was applied.');
        }

        $this->service->applyChunk($job);

        return redirect()->route('bulk.jobs.show', $job->id)
            ->with('flash_success', $job->status === 'completed'
                ? "Job #{$job->id} finished: {$job->applied_create_count} created, {$job->applied_update_count} updated, {$job->failed_count} failed."
                : "Job #{$job->id} is applying — progress is saved row by row, you can leave and resume it from the hub.");
    }

    public function apply(BulkImportJob $job)
    {
        if ($job->status !== 'applying') {
            return back()->with('flash_danger', 'This job is not in the middle of applying.');
        }

        $this->service->applyChunk($job);

        return redirect()->route('bulk.jobs.show', $job->id)
            ->with('flash_success', $job->status === 'completed'
                ? "Job #{$job->id} finished: {$job->applied_create_count} created, {$job->applied_update_count} updated, {$job->failed_count} failed."
                : "Job #{$job->id}: another batch applied — " . (int) $job->pendingRows()->count() . ' row(s) still pending.');
    }

    public function discard(BulkImportJob $job)
    {
        $this->service->discard($job);
        return redirect()->route('bulk.index')
            ->with('flash_success', "Job #{$job->id} discarded. Rows it had already applied are not undone.");
    }

    /**************** ROLLBACK (Wave 9) ****************/

    public function rollback(BulkImportJob $job)
    {
        $result = $this->service->rollback($job);

        if (isset($result['error'])) {
            return back()->with('flash_danger', $result['error'] . ' Finish applying it first, then roll it back.');
        }

        if ($result['rolled_back'] === 0) {
            return back()->with('flash_danger', "Job #{$job->id}: nothing could be rolled back. " . implode(' ', $result['skipped']));
        }

        $msg = "Job #{$job->id} rolled back: {$result['rolled_back']} row(s) reversed.";
        if ($result['skipped']) {
            $msg .= ' Skipped: ' . implode(' ', $result['skipped']);
        }
        if ($result['class_changed'] > 0) {
            $msg .= " Note: {$result['class_changed']} row(s) had changed a student's class — values are restored, but the marks deleted by that class change cannot be brought back.";
        }

        return redirect()->route('bulk.jobs.show', $job->id)->with('flash_success', $msg);
    }

    /**************** DOWNLOADS ****************/

    /** Error / skip / failure report for one job (CsvExport, formula-safe). */
    public function errors(BulkImportJob $job)
    {
        $rows = [];
        $problem = $job->rows()->whereIn('verdict', ['invalid', 'duplicate', 'unmatched', 'failed'])
            ->orderBy('row_number')->get();

        foreach ($problem as $r) {
            if ($r->verdict === 'invalid' && $r->errors) {
                foreach ($r->errors as $e) {
                    $rows[] = [$r->row_number, $e['field'] ?? '', $e['value'] ?? '', $e['message'] ?? ''];
                }
            } elseif ($r->verdict === 'failed') {
                $rows[] = [$r->row_number, '', '', 'Could not be saved: ' . $r->failure];
            } else {
                $e = $r->errors[0] ?? null;
                $rows[] = [$r->row_number, $e['field'] ?? '', $e['value'] ?? '', $e['message'] ?? ucfirst($r->verdict)];
            }
        }

        return CsvExport::download("bulk-job-{$job->id}-report.csv", ['Row', 'Field', 'Value', 'Problem'], $rows);
    }

