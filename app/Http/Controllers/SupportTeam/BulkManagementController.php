/**
 * Bulk Management hub (Bulk System Phase A — docs/BULK_SYSTEM_AUDIT.md).
 *
 * One staged pipeline for CSV bulk work: Bulk Add Students, Bulk Edit
 * Students, Bulk Add Staff. Uploads are staged + validated into a
 * preview; nothing is written until the admin confirms with the job's
 * single-use token; apply then runs in persisted 100-row chunks.
 *
 * Gates follow the audit §8.1 exactly: hub/history/reports are teamSA
 * reads; upload, confirm/apply and discard are teamSAWrite (the school
 * Admin). The routes are deliberately NOT on the Super Admin's
 * PlatformOnly allowlist — bulk data is a school record, and the
 * platform owner sees numbers, not records.
 */
class BulkManagementController extends Controller
{
    protected $service;

    public function __construct(BulkImportService $service)
    {
        $this->middleware('teamSA');
        $this->middleware('teamSAWrite', ['only' => [
            'studentsAdd', 'studentsEdit', 'staffAdd', 'staffEdit', 'upload',
            'confirm', 'apply', 'discard', 'rollback',
        ]]);
        $this->service = $service;
    }

