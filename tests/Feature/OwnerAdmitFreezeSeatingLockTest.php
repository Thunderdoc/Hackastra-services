/**
 * ONE-TIME GENERATION, round 2 (owner standing rule 2026-11-08,
 * freeze + seating lock approved by the owner the same day):
 *
 *  - ADMIT CARD FREEZE: publishing an exam's admit cards
 *    snapshots one payload per student in scope
 *    (admit_card_snapshots). Student/parent self-service renders
 *    the SNAPSHOT, so post-publish live edits — a section
 *    transfer, a Settings branding change, a date sheet
 *    corrected through the Principal return path — cannot
 *    rewrite a released card. Unpublish hides; re-publish
 *    re-freezes. The fee gate stays LIVE (a due student's frozen
 *    card still blocks), and office/bulk printing stays on live
 *    data (the correction surface).
 *  - SEATING LOCK: a SUBMITTED or PUBLISHED seating plan refuses
 *    regeneration (plan + seats untouched), mirroring the
 *    date-sheet lock; the Principal's audited return is the only
 *    way back to draft. Drafts regenerate freely.
 */
class OwnerAdmitFreezeSeatingLockTest extends TestCase
{
    use DatabaseTransactions;

    /* ---------------- helpers ---------------- */

    protected function userByEmail($email)
    {
        return User::where('email', $email)->firstOrFail();
    }

    protected function admin() { return $this->userByEmail('admin@hackstra.app'); }
    protected function principal() { return $this->userByEmail('principal@hackstra.app'); }
    protected function teacher() { return $this->userByEmail('teacher@hackstra.app'); }
    protected function parentUser() { return $this->userByEmail('parent@hackstra.app'); }

    protected function makeUser($type, $tag, $name = null)
    {
        return User::create([
            'name' => $name ?: ('AFZ ' . ucfirst($tag)),
            'email' => 'afz_' . $tag . '@example.test',
            'username' => 'afz_' . $tag,
            'password' => Hash::make('afz-pass'),
            'user_type' => $type,
            'code' => 'AFZ-' . strtoupper($tag),
        ]);
    }

    /** Class with sections A + B, two subjects, one student in A. */
    protected function admitWorld($tag = 'w1')
    {
        $class = MyClass::create(['name' => 'AFZ Class ' . $tag]);
        $secA = Section::create(['name' => 'A', 'my_class_id' => $class->id, 'teacher_id' => $this->teacher()->id]);
        $secB = Section::create(['name' => 'B', 'my_class_id' => $class->id, 'teacher_id' => $this->teacher()->id]);
        $subjects = [];
        foreach (['AFZ Maths ' . $tag, 'AFZ English ' . $tag] as $i => $name) {
            $subjects[] = Subject::create([
                'name' => $name, 'my_class_id' => $class->id,
                'teacher_id' => $this->teacher()->id,
                'slug' => 'afz-' . $class->id . '-' . $i . '-' . uniqid(),
                'periods_per_week' => 5,
            ]);
        }
        $user = $this->makeUser('student', $tag . '_s1', 'AFZ Student ' . $tag);
        $sr = StudentRecord::create([
            'user_id' => $user->id, 'my_class_id' => $class->id,
            'section_id' => $secA->id, 'adm_no' => 'AFZ-' . strtoupper($tag) . '-1',
            'session' => Qs::getCurrentSession(), 'year_admitted' => '2026', 'grad' => 0,
        ]);
        $exam = Exam::create([
            'name' => 'AFZ Exam ' . $tag, 'term' => 1,
            'year' => Qs::getCurrentSession(), 'my_class_id' => $class->id,
        ]);
        // Dated sheet so the card carries real dates.
        foreach ($subjects as $i => $subject) {
            ExamDate::create([
                'exam_id' => $exam->id, 'my_class_id' => $class->id, 'subject_id' => $subject->id,
                'exam_date' => '2027-03-0' . ($i + 1), 'start_time' => '09:00:00',
            ]);
        }

        return [$exam, $class, $secA, $secB, $subjects, $user, $sr];
    }

    /** Extract the rendered card markup (the deterministic part). */
    protected function cardSegment($html)
    {
        $start = strpos($html, '<div class="admit-card">');
        $end = strpos($html, 'Generated by Hackstra');
        $this->assertNotFalse($start, 'Card markup missing');
        $this->assertNotFalse($end, 'Card genline missing');

        return substr($html, $start, $end - $start);
    }

    /* ---------------- Part 1: admit-card freeze ---------------- */

    public function test_publish_freezes_and_live_edits_cannot_rewrite_the_card()
    {
        [$exam, $class, $secA, $secB, $subjects, $user, $sr] = $this->admitWorld('frz');

        // Publish through the real route (Principal only).
        $this->actingAs($this->principal())
            ->post(route('exams.publish_admit_cards', $exam->id))
            ->assertRedirect();
        $this->assertTrue((bool) $exam->fresh()->admit_cards_published);
        $snap = AdmitCardSnapshot::where('exam_id', $exam->id)
            ->where('student_id', $user->id)->first();
        $this->assertNotNull($snap, 'Publish must freeze a snapshot for every student in scope');
        $this->assertSame('A', $snap->payload['student']['section_name']);
        $this->assertSame($this->principal()->id, (int) $snap->frozen_by);

        // The frozen render.
        $before = $this->actingAs($user)->get(route('admit_cards.my_card', [$exam->id, $user->id]));
        $before->assertOk();
        $before->assertViewIs('pages.support_team.exams.admit_print');
        $cardBefore = $this->cardSegment($before->getContent());
        $this->assertStringContainsString('Mon, 01 Mar 2027', $cardBefore);

        /* Live edits AFTER the freeze:
           (a) the student is transferred to section B;
           (b) the school is renamed in Settings;
           (c) the date sheet is published, returned by the
               Principal for correction, and a date is moved. */
        $sr->update(['section_id' => $secB->id]);
        Setting::updateOrCreate(['type' => 'system_name'], ['description' => 'Renamed Academy AFZ']);
        $this->actingAs($this->admin())->post(route('exam_dates.submit'), [
            'exam_id' => $exam->id, 'class_id' => $class->id,
        ])->assertRedirect();
        $this->actingAs($this->principal())->post(route('exam_dates.approve'), [
            'exam_id' => $exam->id, 'class_id' => $class->id,
        ])->assertRedirect();
        $this->actingAs($this->principal())->post(route('exam_dates.return'), [
            'exam_id' => $exam->id, 'class_id' => $class->id,
        ])->assertRedirect();
        ExamDate::where('exam_id', $exam->id)->where('subject_id', $subjects[0]->id)
            ->update(['exam_date' => '2027-04-15']);

        // The self-service card is byte-identical to the frozen one.
        $after = $this->actingAs($user)->get(route('admit_cards.my_card', [$exam->id, $user->id]));
        $after->assertOk();
        $cardAfter = $this->cardSegment($after->getContent());
        $this->assertSame($cardBefore, $cardAfter,
            'A released card must not change when its live sources do');
        $this->assertStringNotContainsString('Renamed Academy AFZ', $cardAfter);

        // The my-cards list shows the exam identity as frozen, too.
        $list = $this->actingAs($user)->get(route('admit_cards.my'));
        $list->assertSee('AFZ Exam frz', false);

        // Office printing is the correction surface: still LIVE.
        $office = $this->actingAs($this->admin())
            ->get(route('admit_cards.print', ['exam' => $exam->id, 'class' => $class->id, 'student' => $user->id]));
        $office->assertOk();
        $office->assertSee('Renamed Academy AFZ', false);
        $office->assertSee('Thu, 15 Apr 2027', false);
    }

    public function test_unpublish_hides_and_republish_refreezes()
    {
        [$exam, $class, $secA, $secB, $subjects, $user, $sr] = $this->admitWorld('rfrz');

        $this->actingAs($this->principal())->post(route('exams.publish_admit_cards', $exam->id));
        $card = $this->actingAs($user)->get(route('admit_cards.my_card', [$exam->id, $user->id]));
        $card->assertViewIs('pages.support_team.exams.admit_print');
        $this->assertStringContainsString('<td>A</td>', $this->cardSegment($card->getContent()));

        // Unpublish: the shared not-published state returns, and
        // the snapshot rows are KEPT (hidden by the flag).
        $this->actingAs($this->principal())->post(route('exams.unpublish_admit_cards', $exam->id));
        $hidden = $this->actingAs($user)->get(route('admit_cards.my_card', [$exam->id, $user->id]));
        $hidden->assertViewIs('pages.support_team.not_published');
        $this->assertSame(1, AdmitCardSnapshot::where('exam_id', $exam->id)
            ->where('student_id', $user->id)->count(), 'Unpublish keeps the frozen rows');

        // Transfer while unpublished, then re-publish: re-freeze.
        $sr->update(['section_id' => $secB->id]);
        $this->actingAs($this->principal())->post(route('exams.publish_admit_cards', $exam->id));
        $snap = AdmitCardSnapshot::where('exam_id', $exam->id)
            ->where('student_id', $user->id)->first();
        $this->assertSame('B', $snap->payload['student']['section_name'],
            'Re-publishing re-freezes from live data');
        $card2 = $this->actingAs($user)->get(route('admit_cards.my_card', [$exam->id, $user->id]));
        $this->assertStringContainsString('<td>B</td>', $this->cardSegment($card2->getContent()));
    }

    public function test_fee_gate_stays_live_on_a_frozen_card_seeded_world()
    {
        // Seeded world: exam 1 is global; record 1 owes nothing,
        // record 2 owes ₹14,400 (OwnerPublicationGateTest anchors).
        $sr1 = StudentRecord::findOrFail(1);
        $sr2 = StudentRecord::findOrFail(2);

        $this->actingAs($this->principal())
            ->post(route('exams.publish_admit_cards', 1))
            ->assertRedirect();

        $this->assertGreaterThan(3000, AdmitCardSnapshot::where('exam_id', 1)->count(),
            'A global exam freezes every active student');
        $this->assertNotNull(AdmitCardSnapshot::where('exam_id', 1)
            ->where('student_id', $sr1->user_id)->first());

        // Paid child: the frozen card renders.
        $paid = $this->actingAs($this->parentUser())
            ->get(route('admit_cards.my_card', ['exam' => 1, 'student_id' => $sr1->user_id]));
        $paid->assertOk();
        $paid->assertViewIs('pages.support_team.exams.admit_print');

        // Owing child: the fee gate is LIVE — the frozen card
        // still blocks until the dues clear.
        $owing = $this->actingAs($this->parentUser())
            ->get(route('admit_cards.my_card', ['exam' => 1, 'student_id' => $sr2->user_id]));
        $owing->assertOk();
        $owing->assertViewIs('pages.support_team.fee_blocked');
        $owing->assertSee('14,400', false);
    }

    public function test_admin_publish_attempt_freezes_nothing()
    {
        [$exam] = $this->admitWorld('noadm');

        $this->actingAs($this->admin())
            ->post(route('exams.publish_admit_cards', $exam->id))
            ->assertForbidden();
        $this->assertFalse((bool) $exam->fresh()->admit_cards_published);
        $this->assertSame(0, AdmitCardSnapshot::where('exam_id', $exam->id)->count());
    }

    /* ---------------- Part 2: seating-plan lock ---------------- */

    protected function seatingWorld($tag = 'sl1')
    {
        $class = MyClass::create(['name' => 'AFZ Seat Class ' . $tag]);
        $section = Section::create(['name' => 'A', 'my_class_id' => $class->id, 'teacher_id' => $this->teacher()->id]);
        $subject = Subject::create([
            'name' => 'AFZ Seat Sub ' . $tag, 'my_class_id' => $class->id,
            'teacher_id' => $this->teacher()->id,
            'slug' => 'afz-seat-' . $class->id . '-' . uniqid(), 'periods_per_week' => 5,
        ]);
        for ($i = 1; $i <= 3; $i++) {
            [, $sr] = $this->makeStudentRow($class, $section, $tag . '_s' . $i, (string) (2000 + $i));
        }
        $exam = Exam::create([
            'name' => 'AFZ Seat Exam ' . $tag, 'term' => 1, 'year' => Qs::getCurrentSession(),
        ]);
        ExamDate::create([
            'exam_id' => $exam->id, 'my_class_id' => $class->id, 'subject_id' => $subject->id,
            'exam_date' => '2026-12-10', 'start_time' => '09:00:00',
        ]);
        $room = Room::create(['name' => 'AFZ Seat Hall ' . $tag, 'kind' => 'classroom', 'capacity' => 30]);

        return [$exam, $room];
    }

    protected function makeStudentRow($class, $section, $tag, $admNo)
    {
        $user = $this->makeUser('student', $tag);
        $sr = StudentRecord::create([
            'user_id' => $user->id, 'my_class_id' => $class->id,
            'section_id' => $section->id, 'adm_no' => $admNo,
            'session' => Qs::getCurrentSession(), 'year_admitted' => '2026', 'grad' => 0,
        ]);

        return [$user, $sr];
    }

    protected function generateSeating($exam, $room)
    {
        return $this->actingAs($this->admin())->post(route('exam_seating.generate'), [
            'exam_id' => $exam->id, 'exam_date' => '2026-12-10', 'time_key' => '09:00',
            'mode' => 'separate', 'room_ids' => [$room->id],
        ]);
    }

    public function test_seating_draft_regenerates_freely()
    {
        [$exam, $room] = $this->seatingWorld('drf');
        $this->generateSeating($exam, $room)->assertRedirect();
        $plan = SeatingPlan::where('exam_id', $exam->id)->firstOrFail();
        $this->assertSame(SeatingPlan::DRAFT, $plan->status);

        $this->generateSeating($exam, $room)->assertRedirect();
        $this->assertSame(SeatingPlan::DRAFT, $plan->fresh()->status);
        $this->assertSame(3, SeatingSeat::where('plan_id', $plan->id)->count());
    }

    public function test_seating_submitted_and_published_refuse_regeneration()
    {
        [$exam, $room] = $this->seatingWorld('lck');
        $this->generateSeating($exam, $room)->assertRedirect();
        $plan = SeatingPlan::where('exam_id', $exam->id)->firstOrFail();

        $this->actingAs($this->admin())->post(route('exam_seating.submit', $plan->id));
        $this->assertSame(SeatingPlan::SUBMITTED, $plan->fresh()->status);
        $seats = SeatingSeat::where('plan_id', $plan->id)->count();

        // Submitted: regeneration refused, plan + seats untouched.
        $this->generateSeating($exam, $room)->assertSessionHas('flash_danger');
        $this->assertSame(SeatingPlan::SUBMITTED, $plan->fresh()->status);
        $this->assertSame($seats, SeatingSeat::where('plan_id', $plan->id)->count());

        // Published: same refusal — HTTP and planner level alike.
        $this->actingAs($this->principal())->post(route('exam_seating.approve'), ['plan_id' => $plan->id]);
        $this->assertSame(SeatingPlan::PUBLISHED, $plan->fresh()->status);
        $this->generateSeating($exam, $room)->assertSessionHas('flash_danger');
        $this->assertSame(SeatingPlan::PUBLISHED, $plan->fresh()->status);
        $this->assertSame($seats, SeatingSeat::where('plan_id', $plan->id)->count());

        [$ok, $message] = SeatingPlanner::generate($exam->id, '2026-12-10', '09:00', [$room->id], 'separate', $this->admin()->id);
        $this->assertFalse($ok);
        $this->assertStringContainsString('published by the Principal', $message);
        $this->assertSame(SeatingPlan::PUBLISHED, $plan->fresh()->status);
    }

    public function test_seating_principal_return_reopens_and_is_audited()
    {
        [$exam, $room] = $this->seatingWorld('rtn');
        $this->generateSeating($exam, $room)->assertRedirect();
        $plan = SeatingPlan::where('exam_id', $exam->id)->firstOrFail();
        $this->actingAs($this->admin())->post(route('exam_seating.submit', $plan->id));
        $this->actingAs($this->principal())->post(route('exam_seating.approve'), ['plan_id' => $plan->id]);
        $this->assertSame(SeatingPlan::PUBLISHED, $plan->fresh()->status);

        // Admin cannot return (Principal-only surface).
        $this->actingAs($this->admin())->post(route('exam_seating.return'), ['plan_id' => $plan->id])
            ->assertRedirect(route('dashboard'));
        $this->assertSame(SeatingPlan::PUBLISHED, $plan->fresh()->status);

        // Principal returns: draft again, stamps cleared, audited.
        $this->actingAs($this->principal())->post(route('exam_seating.return'), ['plan_id' => $plan->id])
            ->assertSessionHas('flash_success');
        $plan->refresh();
        $this->assertSame(SeatingPlan::DRAFT, $plan->status);
        $this->assertNull($plan->submitted_at);
        $this->assertNull($plan->approved_by);
        $this->assertDatabaseHas('audit_logs', ['action' => 'exams.seating_returned']);

        // And regeneration lands again.
        $this->generateSeating($exam, $room)->assertRedirect();
        $this->assertSame(SeatingPlan::DRAFT, $plan->fresh()->status);

        // Returning a draft is refused — there is nothing to return.
        $this->actingAs($this->principal())->post(route('exam_seating.return'), ['plan_id' => $plan->id])
            ->assertSessionHas('flash_danger');
        $this->assertSame(SeatingPlan::DRAFT, $plan->fresh()->status);
    }
}
